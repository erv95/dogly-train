// Translations of the same content. To keep this script tractable we provide
// the same structure per language; only the strings differ.
function generateAll(daysMap, translateFn) {
  const out = {};
  for (let d = 1; d <= 30; d++) {
    const ref = daysMap[d];
    out[d] = translateFn(ref, d);
  }
  return out;
}

