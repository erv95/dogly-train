function buildNamespace(lang) {
  const pack = langPacks[lang];
  const dayData = dayDataByLang[lang];
  const ns = {
    catalogIntro: pack.catalogIntro,
    daysLabel: pack.daysLabel,
    daysDone: pack.daysDone,
    inProgress: pack.inProgress,
    completed: pack.completed,
    title: pack.title,
    startCta: pack.startCta,
    notFound: pack.notFound,
    completedTitle: pack.completedTitle,
    completedBody: pack.completedBody,
    allDoneCelebration: pack.allDoneCelebration,
    tapDayHint: pack.tapDayHint,
    dayN: pack.dayN,
    openRelatedCourse: pack.openRelatedCourse,
    markDayDone: pack.markDayDone,
    untickDay: pack.untickDay,
    footHint: pack.footHint,
    difficulty: pack.difficulty,
  };
  for (const tplId of ['obedience_basic_30', 'socialization_30', 'fun_tricks_30', 'mental_active_30']) {
    const days = {};
    for (let d = 1; d <= 30; d++) {
      days[d] = {
        title: dayData[tplId][d].title,
        instruction: dayData[tplId][d].body,
      };
    }
    ns[tplId] = {
      name: pack[tplId].name,
      description: pack[tplId].description,
      days,
    };
  }
  return ns;
}

for (const lang of ['es', 'en', 'fr', 'pt', 'de']) {
  const path = `src/locales/${lang}.json`;
  const j = JSON.parse(readFileSync(path, 'utf8'));
  j.challenges = buildNamespace(lang);
  writeFileSync(path, JSON.stringify(j, null, 2) + '\n', 'utf8');
  console.log('OK', path);
}
